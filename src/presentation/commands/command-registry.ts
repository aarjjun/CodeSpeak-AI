function definition(
  id: string,
  displayName: string,
  voiceAliases: readonly string[],
  description: string,
  requiresEditor: boolean,
  requiresSelection: boolean,
  producesSpeech: boolean,
  requiresConfirmation = false,
): CodeSpeakCommandDefinition {
  return {
    id,
    displayName,
    voiceAliases,
    description,
    requiresEditor,
    requiresSelection,
    producesSpeech,
    requiresConfirmation,
  };
}

export function findCommandByVoiceAlias(
  transcript: string,
): CodeSpeakCommandDefinition | undefined {
  const normalized = normalizeVoiceText(transcript)
    .replace(/^run code speak /u, '')
    .replace(/^code speak /u, '');
  return CODE_SPEAK_COMMANDS.find((command) =>
    command.voiceAliases.some((alias) => normalizeVoiceText(alias) === normalized),
  );
}

export function normalizeVoiceText(value: string): string {
  return value
    .trim()
    .toLocaleLowerCase()
    .replace(/[.,!?]/gu, '')
    .replace(/\bcodespeak\b/gu, 'code speak')
    .replace(/\s+/gu, ' ');
}
